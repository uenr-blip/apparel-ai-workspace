import { execSync } from "node:child_process";
import { getPrisma } from "@/lib/db";
import { seedDatabase } from "../prisma/seed";
import { TEST_DATABASE_URL } from "./database-config";

export async function resetDatabase() {
  process.env.DATABASE_URL = TEST_DATABASE_URL;
  execSync("npx prisma db push --skip-generate", {
    stdio: "pipe",
    env: { ...process.env, DATABASE_URL: TEST_DATABASE_URL },
  });

  const client = getPrisma();
  await client.$transaction([
    client.workflowRead.deleteMany(),
    client.workflowTransfer.deleteMany(),
    client.workflowParticipant.deleteMany(),
    client.workflowRevision.deleteMany(),
    client.workflowStage.deleteMany(),
    client.styleCodeAlias.deleteMany(),
    client.factoryTransfer.deleteMany(),
    client.followChange.deleteMany(),
    client.patternHandoff.deleteMany(),
    client.gLSourceClaim.deleteMany(),
    client.gLLine.deleteMany(),
    client.gLJournal.deleteMany(),
    client.gLPeriod.deleteMany(),
    client.gLAccount.deleteMany(),
    client.gLBook.deleteMany(),
    client.treasuryLeg.deleteMany(),
    client.treasuryRefund.deleteMany(),
    client.treasuryFx.deleteMany(),
    client.orderCostTag.deleteMany(),
    client.materialEvent.deleteMany(),
    client.materialUse.deleteMany(),
    client.materialLotOrigin.deleteMany(),
    client.materialValuation.deleteMany(),
    client.materialReceipt.deleteMany(),
    client.tradeAllocation.deleteMany(),
    client.tradeAdjustment.deleteMany(),
    client.tradeDocument.deleteMany(),
    client.tradeBill.deleteMany(),
    client.tradeCash.deleteMany(),
    client.tradeContract.deleteMany(),
    client.tradeOperation.deleteMany(),
    client.tradeBook.deleteMany(),
    client.styleSeason.deleteMany(),
    client.season.deleteMany(),
    client.knowledgeReuseEvent.deleteMany(),
    client.designVariant.deleteMany(),
    client.designRound.deleteMany(),
    client.designAsset.deleteMany(),
    client.designProject.deleteMany(),
    client.orderMerchStyle.deleteMany(),
    client.orderMerchSheet.deleteMany(),
    client.developmentCandidate.deleteMany(),
    client.patternSample.deleteMany(),
    client.patternRevision.deleteMany(),
    client.developmentProject.deleteMany(),
    client.actionExecution.deleteMany(),
    client.auditEvent.deleteMany(),
    client.taskItem.deleteMany(),
    client.purchaseDraft.deleteMany(),
    client.inventoryAllocation.deleteMany(),
    client.packingCartonLine.deleteMany(),
    client.packingCarton.deleteMany(),
    client.packingPlan.deleteMany(),
    client.factoryReconDraft.deleteMany(),
    client.inventoryMovement.deleteMany(),
    client.styleVersionAttachment.deleteMany(),
    client.productionQtyLine.deleteMany(),
    client.productionQty.deleteMany(),
    client.orderSizeQty.deleteMany(),
    client.orderColorQty.deleteMany(),
    client.orderLine.deleteMany(),
    client.confirmationRecord.deleteMany(),
    client.bomLine.deleteMany(),
    client.sku.deleteMany(),
    client.styleVersion.deleteMany(),
    client.salesOrder.deleteMany(),
    client.sourceFragment.deleteMany(),
    client.actionProposal.deleteMany(),
    client.aiJob.deleteMany(),
    client.sourceDocument.deleteMany(),
    client.supplierQuote.deleteMany(),
    client.inventoryLot.deleteMany(),
    client.user.deleteMany(),
    client.customer.deleteMany(),
    client.party.deleteMany(),
    client.material.deleteMany(),
    client.style.deleteMany(),
    client.styleOption.deleteMany({ where: { parentId: { not: null } } }),
    client.styleOption.deleteMany(),
    client.designer.deleteMany(),
    client.sizeScale.deleteMany(),
    client.organizationPolicy.deleteMany(),
    client.organization.deleteMany(),
  ]);
  await seedDatabase(client);
}
